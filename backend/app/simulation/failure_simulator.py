def reduce_resources(
    state: ScenarioState,
    field: str,
    amount: int,
    config: Optional[Dict[str, Any]] = None,
) -> SimulationDiff:
    """
    Event: reduce_resources (field and amount, e.g. rescue_teams 3 -> 1)
    Sets resource field to specified amount.
    Cumulative until reset.
    """
    baseline = ensure_baseline_initialized(state, config=config)

    valid_fields = {"rescue_teams", "ambulances", "boats", "food_packets", "medical_kits"}
    if field not in valid_fields:
        raise ValueError(f"Invalid resource field '{field}'. Expected one of {valid_fields}")

    old_val = getattr(state.resources, field)
    setattr(state.resources, field, int(amount))

    current_plan = run_simulation(state, config=config)

    diff = compute_diff(
        baseline=baseline,
        current=current_plan,
        event_type="reduce_resources",
        event_id=field,
        event_details={"field": field, "old_value": old_val, "new_value": amount},
    )
    return diff


def reset(
    state: ScenarioState,
    config: Optional[Dict[str, Any]] = None,
) -> SimulationDiff:
    """
    Reset scenario state back to baseline conditions:
    - Clears all cumulative failure sets (bridges, edges, shelters, hospitals).
    - Restores original shelter capacities.
    - Restores original resources.
    - Restores baseline severity.
    - Re-simulates and verifies baseline restoration.
    """
    baseline = ensure_baseline_initialized(state, config=config)

    # Clear cumulative failure collections
    state.clear_failures()

    # Restore shelter capacities
    if hasattr(state, "_orig_shelter_capacities") and state._orig_shelter_capacities:
        for s in state.shelters:
            if s.id in state._orig_shelter_capacities:
                s.capacity = state._orig_shelter_capacities[s.id]

    if hasattr(state, "_filled_shelters"):
        state._filled_shelters.clear()

    # Restore resources
    if hasattr(state, "_orig_resources") and state._orig_resources:
        for k, v in state._orig_resources.items():
            setattr(state.resources, k, v)

    # Restore severity
    if hasattr(state, "_orig_severity") and state._orig_severity is not None:
        state.severity = state._orig_severity

    clear_evacuation_cache()
    current_plan = run_simulation(state, config=config)

    diff = compute_diff(
        baseline=baseline,
        current=current_plan,
        event_type="reset",
        event_id="reset",
        event_details={},
    )
    return diff


def apply_failure(
    state: ScenarioState,
    event: Union[FailureEventRequest, Dict[str, Any]],
    config: Optional[Dict[str, Any]] = None,
) -> SimulationDiff:
    """
    Unified entry point to apply any failure event to ScenarioState.
    Dispatches to appropriate handler and returns SimulationDiff (which includes .plan).
    """
    if isinstance(event, dict):
        event = FailureEventRequest(**event)

    ev_type = event.type
    if ev_type == "block_bridge":
        if not event.id:
            raise ValueError("block_bridge requires bridge 'id'")
        return block_bridge(state, bridge_id=event.id, config=config)
    elif ev_type == "block_edge":
        edge = event.edge
        if edge is None and event.id:
            try:
                edge = [int(x) for x in event.id.replace("->", ",").split(",")]
            except Exception:
                raise ValueError(f"Cannot parse edge from id '{event.id}'")
        if not edge or len(edge) < 2:
            raise ValueError("block_edge requires 'edge': [u, v]")
        return block_edge(state, edge=edge, config=config)
    elif ev_type == "fail_shelter":
        if not event.id:
            raise ValueError("fail_shelter requires shelter 'id'")
        return fail_shelter(state, shelter_id=event.id, config=config)
    elif ev_type == "fill_shelter":
        if not event.id:
            raise ValueError("fill_shelter requires shelter 'id'")
        return fill_shelter(state, shelter_id=event.id, config=config)
    elif ev_type == "fail_hospital":
        if not event.id:
            raise ValueError("fail_hospital requires hospital 'id'")
        return fail_hospital(state, hospital_id=event.id, config=config)
    elif ev_type == "reduce_resources":
        field = event.field or event.id
        if not field or event.amount is None:
            raise ValueError("reduce_resources requires 'field' (or 'id') and 'amount'")
        return reduce_resources(state, field=field, amount=event.amount, config=config)
    elif ev_type == "reset":
        return reset(state, config=config)
    else:
        raise ValueError(f"Unknown failure event type '{ev_type}'")
