def block_bridge(
    state: ScenarioState,
    bridge_id: str,
    config: Optional[Dict[str, Any]] = None,
) -> SimulationDiff:
    """
    Event: block_bridge (B1, B2, B3)
    Removes bridge edges from road graph and recalculates simulation.
    Cumulative until reset.
    """
    baseline = ensure_baseline_initialized(state, config=config)

    bridge = next((b for b in state.bridges if b.id == bridge_id), None)
    if bridge is None:
        raise ValueError(f"Unknown bridge id '{bridge_id}'")

    state.failed_bridges.add(bridge_id)
    edge_count = 0
    for edge in bridge.edges:
        u, v = int(edge[0]), int(edge[1])
        state.blocked_edges.add((u, v))
        edge_count += 1

    clear_evacuation_cache()
    current_plan = run_simulation(state, config=config)

    diff = compute_diff(
        baseline=baseline,
        current=current_plan,
        event_type="block_bridge",
        event_id=bridge_id,
        event_details={"bridge_name": bridge.name, "edge_count": edge_count},
    )
    return diff


def block_edge(
    state: ScenarioState,
    edge: Union[Tuple[int, int], List[int]],
    config: Optional[Dict[str, Any]] = None,
) -> SimulationDiff:
    """
    Event: block_edge ([u, v])
    Removes a single road edge from routing and recalculates simulation.
    Cumulative until reset.
    """
    baseline = ensure_baseline_initialized(state, config=config)

    u, v = int(edge[0]), int(edge[1])
    state.blocked_edges.add((u, v))

    clear_evacuation_cache()
    current_plan = run_simulation(state, config=config)

    diff = compute_diff(
        baseline=baseline,
        current=current_plan,
        event_type="block_edge",
        event_id=f"{u}->{v}",
        event_details={"edge": [u, v]},
    )
    return diff


