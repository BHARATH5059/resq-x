def ensure_baseline_initialized(
    state: ScenarioState,
    config: Optional[Dict[str, Any]] = None,
) -> SimulationPlan:
    """Ensure baseline simulation plan and original attributes exist on state."""
    # Ensure baseline tracking metadata attributes exist on state
    if not hasattr(state, "_orig_shelter_capacities") or state._orig_shelter_capacities is None:
        state._orig_shelter_capacities = {s.id: int(s.capacity) for s in state.shelters}
    if not hasattr(state, "_orig_resources") or state._orig_resources is None:
        state._orig_resources = {
            "rescue_teams": int(state.resources.rescue_teams),
            "ambulances": int(state.resources.ambulances),
            "boats": int(state.resources.boats),
            "food_packets": int(state.resources.food_packets),
            "medical_kits": int(state.resources.medical_kits),
        }
    if not hasattr(state, "_orig_severity") or state._orig_severity is None:
        state._orig_severity = float(state.severity)
    if not hasattr(state, "_filled_shelters") or state._filled_shelters is None:
        state._filled_shelters = set()

    if state.baseline is None:
        state.baseline = run_simulation(state, config=config, save_as_baseline=True)

    return state.baseline


def run_simulation(
    state: ScenarioState,
    config: Optional[Dict[str, Any]] = None,
    save_as_baseline: bool = False,
) -> SimulationPlan:
    """
    Run full simulation pipeline across Modules 1 to 3:
    1. Module 1: Risk Assessment
    2. Module 2: Evacuation Routing
    3. Module 3: Resource & Shelter Optimization
    Optionally stores result as state.baseline.
    """
    risk = run_risk_engine(state, config=config)
    routes = compute_evacuation_routes(state, config=config)
    allocation = optimize_resources(
        state, risk_result=risk, routing_result=routes, config=config
    )

    plan = SimulationPlan(
        severity=float(state.severity),
        risk=risk,
        routes=routes,
        allocation=allocation,
        unmet=int(allocation.totals.total_unmet_people),
        totals=allocation.totals,
    )

    if save_as_baseline or state.baseline is None:
        state.baseline = plan
        if not hasattr(state, "_orig_shelter_capacities") or not state._orig_shelter_capacities:
            state._orig_shelter_capacities = {s.id: int(s.capacity) for s in state.shelters if s.capacity > 0}
        else:
            for s in state.shelters:
                if s.capacity > 0:
                    state._orig_shelter_capacities[s.id] = int(s.capacity)

        if not hasattr(state, "_orig_resources") or not state._orig_resources:
            state._orig_resources = {
                "rescue_teams": int(state.resources.rescue_teams),
                "ambulances": int(state.resources.ambulances),
                "boats": int(state.resources.boats),
                "food_packets": int(state.resources.food_packets),
                "medical_kits": int(state.resources.medical_kits),
            }
        state._orig_severity = float(state.severity)
        state._filled_shelters = set()


    return plan


def compute_diff(
    baseline: SimulationPlan,
    current: SimulationPlan,
    event_type: str,
    event_id: Optional[str] = None,
    event_details: Optional[Dict[str, Any]] = None,
) -> SimulationDiff:
    """
    Compute structured diff between baseline simulation and current simulation.
    Includes:
    - per zone (route changed, old and new route length, old and new assigned shelters, unmet before and after)
    - totals (people assigned, rescued by boat, unmet, total travel cost, before and after)
    - resource movements (which team, ambulance and supply assignments changed)
    - plain-language change messages generated by deterministic rules (no LLM)
    """
    event_details = event_details or {}
    messages: List[str] = []

    # 1. Event trigger message
    if event_type == "block_bridge":
        b_name = event_details.get("bridge_name", event_id)
        e_count = event_details.get("edge_count", 0)
        messages.append(
            f"Bridge {event_id} ({b_name}) blocked: {e_count} road edges removed from network."
        )
    elif event_type == "block_edge":
        edge = event_details.get("edge", event_id)
        messages.append(f"Road edge {edge} blocked manually.")
    elif event_type == "fail_shelter":
        s_name = event_details.get("shelter_name", event_id)
        messages.append(f"Shelter {event_id} ({s_name}) failed and is unavailable.")
    elif event_type == "fill_shelter":
        s_name = event_details.get("shelter_name", event_id)
        messages.append(
            f"Shelter {event_id} ({s_name}) filled to capacity (capacity set to 0)."
        )
    elif event_type == "fail_hospital":
        h_name = event_details.get("hospital_name", event_id)
        messages.append(f"Hospital {event_id} ({h_name}) failed and is unavailable.")
    elif event_type == "reduce_resources":
        field = event_details.get("field", event_id)
        old_val = event_details.get("old_value", "?")
        new_val = event_details.get("new_value", "?")
        messages.append(f"Resource '{field}' reduced from {old_val} to {new_val}.")
    elif event_type == "reset":
        messages.append("Scenario state reset to baseline conditions.")

    # 2. Zone diffs
    zones_diff: Dict[str, ZoneDiff] = {}
    base_zones_map = {z.zone_id: z for z in baseline.allocation.zones}
    curr_zones_map = {z.zone_id: z for z in current.allocation.zones}

    for zid, curr_z in curr_zones_map.items():
        base_z = base_zones_map.get(zid)
        if base_z is None:
            continue

        old_unmet = int(base_z.unmet_people)
        new_unmet = int(curr_z.unmet_people)

        old_assigned = [
            {
                "shelter_id": sa.shelter_id,
                "shelter_name": sa.shelter_name,
                "people": int(sa.people),
                "route_cost": float(sa.route_cost),
                "route_length": float(sa.route_length),
            }
            for sa in base_z.shelter_assignments
        ]
        new_assigned = [
            {
                "shelter_id": sa.shelter_id,
                "shelter_name": sa.shelter_name,
                "people": int(sa.people),
                "route_cost": float(sa.route_cost),
                "route_length": float(sa.route_length),
            }
            for sa in curr_z.shelter_assignments
        ]

        old_len: Optional[float] = None
        if base_z.assigned_to_shelters > 0 and base_z.shelter_assignments:
            old_len = sum(
                sa.people * sa.route_length for sa in base_z.shelter_assignments
            ) / float(base_z.assigned_to_shelters)

        new_len: Optional[float] = None
        if curr_z.assigned_to_shelters > 0 and curr_z.shelter_assignments:
            new_len = sum(
                sa.people * sa.route_length for sa in curr_z.shelter_assignments
            ) / float(curr_z.assigned_to_shelters)

        # Determine if route changed:
        # Check assigned shelters distribution change
        old_alloc = {sa.shelter_id: sa.people for sa in base_z.shelter_assignments}
        new_alloc = {sa.shelter_id: sa.people for sa in curr_z.shelter_assignments}
        alloc_changed = old_alloc != new_alloc

        # Check path change to assigned shelters
        path_changed = False
        for sid in new_alloc:
            base_r = baseline.routes.routes.get(zid, {}).get(sid)
            curr_r = current.routes.routes.get(zid, {}).get(sid)
            if base_r and curr_r:
                if base_r.path != curr_r.path:
                    path_changed = True
                    break

        boat_changed = base_z.rescued_by_boat != curr_z.rescued_by_boat
        route_changed = alloc_changed or path_changed or boat_changed

        zones_diff[zid] = ZoneDiff(
            zone_id=zid,
            zone_name=curr_z.name,
            route_changed=route_changed,
            old_route_length=round(old_len, 2) if old_len is not None else None,
            new_route_length=round(new_len, 2) if new_len is not None else None,
            old_assigned_shelters=old_assigned,
            new_assigned_shelters=new_assigned,
            old_unmet=old_unmet,
            new_unmet=new_unmet,
        )

        # Rule-based messages per zone
        if route_changed:
            if base_z.assigned_to_shelters > 0 and curr_z.assigned_to_shelters == 0:
                if curr_z.rescued_by_boat > 0:
                    messages.append(
                        f"Zone {zid} ({curr_z.name}): road routes lost; {curr_z.rescued_by_boat} evacuees rescued by boat."
                    )
                else:
                    messages.append(
                        f"Zone {zid} ({curr_z.name}): road routes cut off; all {curr_z.affected_people} evacuees unmet."
                    )
            elif alloc_changed:
                old_str = (
                    ", ".join(f"{sa.shelter_id} ({sa.people})" for sa in base_z.shelter_assignments)
                    or "None"
                )
                new_str = (
                    ", ".join(f"{sa.shelter_id} ({sa.people})" for sa in curr_z.shelter_assignments)
                    or "None"
                )
                messages.append(
                    f"Zone {zid} ({curr_z.name}): evacuees reassigned from [{old_str}] to [{new_str}]."
                )
            elif path_changed and old_len is not None and new_len is not None:
                delta_m = new_len - old_len
                messages.append(
                    f"Zone {zid} ({curr_z.name}): route rerouted. Length changed from {old_len:.0f}m to {new_len:.0f}m ({delta_m:+.0f}m)."
                )

        if new_unmet > old_unmet:
            messages.append(
                f"Zone {zid} ({curr_z.name}): unmet evacuees increased by {new_unmet - old_unmet} (from {old_unmet} to {new_unmet})."
            )

    # 3. Totals diff
    b_tot = baseline.totals
    c_tot = current.totals

    assigned_diff = MetricBeforeAfter(
        before=float(b_tot.total_assigned_to_shelters),
        after=float(c_tot.total_assigned_to_shelters),
        delta=float(c_tot.total_assigned_to_shelters - b_tot.total_assigned_to_shelters),
    )
    boat_diff = MetricBeforeAfter(
        before=float(b_tot.total_rescued_by_boat),
        after=float(c_tot.total_rescued_by_boat),
        delta=float(c_tot.total_rescued_by_boat - b_tot.total_rescued_by_boat),
    )
    unmet_diff = MetricBeforeAfter(
        before=float(b_tot.total_unmet_people),
        after=float(c_tot.total_unmet_people),
        delta=float(c_tot.total_unmet_people - b_tot.total_unmet_people),
    )
    cost_diff = MetricBeforeAfter(
        before=round(float(b_tot.total_travel_cost), 2),
        after=round(float(c_tot.total_travel_cost), 2),
        delta=round(float(c_tot.total_travel_cost - b_tot.total_travel_cost), 2),
    )

    totals_diff = TotalsDiff(
        people_assigned=assigned_diff,
        rescued_by_boat=boat_diff,
        unmet=unmet_diff,
        total_travel_cost=cost_diff,
    )

    # Totals summary messages
    if unmet_diff.delta > 0:
        messages.append(
            f"Overall unmet people increased by {int(unmet_diff.delta)} (from {int(unmet_diff.before)} to {int(unmet_diff.after)})."
        )
    elif unmet_diff.delta < 0:
        messages.append(
            f"Overall unmet people decreased by {int(-unmet_diff.delta)} (from {int(unmet_diff.before)} to {int(unmet_diff.after)})."
        )

    if assigned_diff.delta != 0:
        messages.append(
            f"Total people assigned to shelters changed by {int(assigned_diff.delta):+d} (from {int(assigned_diff.before)} to {int(assigned_diff.after)})."
        )

    if cost_diff.delta != 0:
        messages.append(
            f"Total road travel cost changed by {cost_diff.delta:+,.1f} (from {cost_diff.before:,.1f} to {cost_diff.after:,.1f})."
        )

    # 4. Resource movements
    team_movements: List[TeamMovement] = []
    ambulance_movements: List[AmbulanceMovement] = []
    supply_movements: List[SupplyMovement] = []

    for zid, curr_z in curr_zones_map.items():
        base_z = base_zones_map.get(zid)
        if base_z is None:
            continue

        # Teams
        if base_z.rescue_team != curr_z.rescue_team:
            action = "assigned" if curr_z.rescue_team else "removed"
            team_movements.append(
                TeamMovement(
                    zone_id=zid,
                    before=base_z.rescue_team,
                    after=curr_z.rescue_team,
                    action=action,
                )
            )
            if action == "removed":
                messages.append(f"Rescue team withdrawn from Zone {zid} ({curr_z.name}) (now unserved).")
            else:
                messages.append(f"Rescue team dispatched to Zone {zid} ({curr_z.name}).")

        # Ambulances
        amb_changed = (base_z.ambulance != curr_z.ambulance) or (
            base_z.hospital_id != curr_z.hospital_id
        )
        if amb_changed:
            if not base_z.ambulance and curr_z.ambulance:
                action = "assigned"
                messages.append(
                    f"Ambulance dispatched to Zone {zid} ({curr_z.name}) paired with Hospital {curr_z.hospital_id} ({curr_z.hospital_name})."
                )
            elif base_z.ambulance and not curr_z.ambulance:
                action = "removed"
                messages.append(
                    f"Ambulance service withdrawn from Zone {zid} ({curr_z.name})."
                )
            else:
                action = "rerouted"
                messages.append(
                    f"Ambulance for Zone {zid} ({curr_z.name}) rerouted from Hospital {base_z.hospital_id} to Hospital {curr_z.hospital_id} ({curr_z.hospital_name})."
                )

            ambulance_movements.append(
                AmbulanceMovement(
                    zone_id=zid,
                    before_ambulance=base_z.ambulance,
                    after_ambulance=curr_z.ambulance,
                    before_hospital_id=base_z.hospital_id,
                    before_hospital_name=base_z.hospital_name,
                    after_hospital_id=curr_z.hospital_id,
                    after_hospital_name=curr_z.hospital_name,
                    action=action,
                )
            )

        # Supplies
        food_delta = curr_z.food_packets - base_z.food_packets
        kits_delta = curr_z.medical_kits - base_z.medical_kits
        if food_delta != 0 or kits_delta != 0:
            supply_movements.append(
                SupplyMovement(
                    zone_id=zid,
                    food_packets_before=base_z.food_packets,
                    food_packets_after=curr_z.food_packets,
                    food_packets_delta=food_delta,
                    medical_kits_before=base_z.medical_kits,
                    medical_kits_after=curr_z.medical_kits,
                    medical_kits_delta=kits_delta,
                )
            )

    resource_movements = ResourceMovements(
        teams=team_movements,
        ambulances=ambulance_movements,
        supplies=supply_movements,
    )

    diff = SimulationDiff(
        event_type=event_type,
        event_id=event_id,
        event_details=event_details,
        zones=zones_diff,
        totals=totals_diff,
        resource_movements=resource_movements,
        messages=messages,
        plan=current,
    )
    return diff


