def fill_shelter(
    state: ScenarioState,
    shelter_id: str,
    config: Optional[Dict[str, Any]] = None,
) -> SimulationDiff:
    """
    Event: fill_shelter (S1..S6)
    Sets shelter capacity to 0 (cannot receive more evacuees).
    Cumulative until reset.
    """
    baseline = ensure_baseline_initialized(state, config=config)

    shelter = next((s for s in state.shelters if s.id == shelter_id), None)
    if shelter is None:
        raise ValueError(f"Unknown shelter id '{shelter_id}'")

    if not hasattr(state, "_filled_shelters") or state._filled_shelters is None:
        state._filled_shelters = set()
    state._filled_shelters.add(shelter_id)

    # Set capacity to 0
    shelter.capacity = 0

    clear_evacuation_cache()
    current_plan = run_simulation(state, config=config)

    diff = compute_diff(
        baseline=baseline,
        current=current_plan,
        event_type="fill_shelter",
        event_id=shelter_id,
        event_details={"shelter_name": shelter.name},
    )
    return diff


