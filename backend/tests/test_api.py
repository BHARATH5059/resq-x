def test_get_scenario_geojson():
    """
    GET /scenario returns static map data as GeoJSON with [lon, lat] coordinates:
    zones, shelters, hospitals, relief base, flood polygons, and crossings as LineStrings.
    """
    resp = client.get("/scenario")
    assert resp.status_code == 200
    data = resp.json()

    # Required top-level keys
    assert "zones" in data
    assert "shelters" in data
    assert "hospitals" in data
    assert "relief_base" in data or "base" in data
    assert "flood_polygons" in data
    assert "bridges" in data or "crossings" in data

    # Zones FeatureCollection
    zones_fc = data["zones"]
    assert zones_fc["type"] == "FeatureCollection"
    assert len(zones_fc["features"]) == 6
    for feat in zones_fc["features"]:
        assert feat["geometry"]["type"] == "Point"
        coords = feat["geometry"]["coordinates"]
        assert len(coords) == 2
        # Coords are [lon, lat]: lon around 80.2, lat around 12.9
        assert 80.0 <= coords[0] <= 81.0
        assert 12.0 <= coords[1] <= 14.0

    # Shelters FeatureCollection
    shelters_fc = data["shelters"]
    assert shelters_fc["type"] == "FeatureCollection"
    assert len(shelters_fc["features"]) == 6

    # Hospitals FeatureCollection
    hospitals_fc = data["hospitals"]
    assert hospitals_fc["type"] == "FeatureCollection"
    assert len(hospitals_fc["features"]) == 4

    # Flood Polygons FeatureCollection
    flood_fc = data["flood_polygons"]
    assert flood_fc["type"] == "FeatureCollection"
    assert len(flood_fc["features"]) == 4
    for feat in flood_fc["features"]:
        assert feat["geometry"]["type"] == "Polygon"

    # Bridges LineStrings FeatureCollection
    bridges_fc = data["bridges"]
    assert bridges_fc["type"] == "FeatureCollection"
    assert len(bridges_fc["features"]) >= 3
    for feat in bridges_fc["features"]:
        assert feat["geometry"]["type"] == "LineString"
        assert len(feat["geometry"]["coordinates"]) >= 2


def test_get_roads_geojson():
    """
    GET /roads returns all road network edges as GeoJSON LineStrings with
    edge_depth, impassable, and blocked properties.
    """
    resp = client.get("/roads")
    assert resp.status_code == 200
    data = resp.json()

    assert data["type"] == "FeatureCollection"
    features = data["features"]
    assert len(features) > 2000

    sample = features[0]
    assert sample["geometry"]["type"] == "LineString"
    props = sample["properties"]
    assert "u" in props
    assert "v" in props
    assert "length" in props
    assert "edge_depth" in props
    assert "impassable" in props
    assert "blocked" in props
    assert isinstance(props["impassable"], bool)
    assert isinstance(props["blocked"], bool)


