def test_item_10_simulate_then_failure_returns_diff():
    """
    Section 10 item 10:
    /simulate then /failure returns a diff where changed fields differ from the baseline.
    """
    sim_resp = client.post("/simulate", json={"severity": 1.0})
    assert sim_resp.status_code == 200
    base_cost = sim_resp.json()["totals"]["total_travel_cost"]

    # Block bridge B1
    fail_resp = client.post("/failure", json={"type": "block_bridge", "id": "B1"})
    assert fail_resp.status_code == 200
    fail_data = fail_resp.json()

    assert "plan" in fail_data
    assert "diff" in fail_data

    diff = fail_data["diff"]
    # Changed fields differ from baseline
    assert diff["zones"]["P2"]["route_changed"] is True
    assert diff["totals"]["total_travel_cost"]["delta"] > 0
    assert diff["totals"]["total_travel_cost"]["after"] > base_cost

    # Plain language change messages generated by rules
    assert len(diff["messages"]) > 0
    assert any("B1" in msg for msg in diff["messages"])

    # Reset
    reset_resp = client.post("/reset")
    assert reset_resp.status_code == 200


def test_unknown_ids_and_validation():
    """
    Test validation of IDs and payloads:
    Unknown IDs return 404 with clear message; invalid payloads return 422.
    """
    # Unknown bridge ID -> 404
    r1 = client.post("/failure", json={"type": "block_bridge", "id": "B99"})
    assert r1.status_code == 404
    assert "B99" in r1.json()["detail"]

    # Unknown shelter ID -> 404
    r2 = client.post("/failure", json={"type": "fail_shelter", "id": "S99"})
    assert r2.status_code == 404
    assert "S99" in r2.json()["detail"]

    r2b = client.post("/failure", json={"type": "fill_shelter", "id": "S99"})
    assert r2b.status_code == 404
    assert "S99" in r2b.json()["detail"]

    # Unknown hospital ID -> 404
    r3 = client.post("/failure", json={"type": "fail_hospital", "id": "H99"})
    assert r3.status_code == 404
    assert "H99" in r3.json()["detail"]

    # Unknown road edge -> 404
    r4 = client.post("/failure", json={"type": "block_edge", "edge": [999999999, 888888888]})
    assert r4.status_code == 404
    assert "not found" in r4.json()["detail"]

    # Unknown failure type -> 422
    r5 = client.post("/failure", json={"type": "invalid_event_type", "id": "B1"})
    assert r5.status_code == 422
    assert "Unknown failure type" in r5.json()["detail"]

    # Invalid resource field -> 422
    r6 = client.post("/failure", json={"type": "reduce_resources", "id": "helicopters", "amount": 1})
    assert r6.status_code == 422
    assert "Invalid resource field" in r6.json()["detail"]

    # Missing amount for reduce_resources -> 422
    r7 = client.post("/failure", json={"type": "reduce_resources", "id": "rescue_teams"})
    assert r7.status_code == 422


def test_full_demo_sequence_via_api_sev_1_25():
    """
    Full demo sequence at severity 1.25 via API:
    1. POST /simulate with severity 1.25 -> establishes baseline.
    2. POST /failure with fill_shelter S1.
    3. POST /failure with block_bridge B1.
    4. POST /failure with fail_hospital H1 -> P4 ambulance reroutes from H1 to H2.
    5. POST /failure with reduce_resources rescue_teams to 1.
    6. POST /reset -> restores baseline plan exactly.
    """
    # 1. Baseline at 1.25
    r_sim = client.post("/simulate", json={"severity": 1.25})
    assert r_sim.status_code == 200
    base_data = r_sim.json()
    assert base_data["totals"]["total_rescued_by_boat"] == 800

    # 2. Fill shelter S1
    r_fill_s1 = client.post("/failure", json={"type": "fill_shelter", "id": "S1"})
    assert r_fill_s1.status_code == 200

    # 3. Block bridge B1
    r_block_b1 = client.post("/failure", json={"type": "block_bridge", "id": "B1"})
    assert r_block_b1.status_code == 200
    diff_b1 = r_block_b1.json()["diff"]
    assert diff_b1["zones"]["P3"]["route_changed"] is True

    # 4. Fail hospital H1
    r_fail_h1 = client.post("/failure", json={"type": "fail_hospital", "id": "H1"})
    assert r_fail_h1.status_code == 200
    diff_h1 = r_fail_h1.json()["diff"]
    # P4 ambulance was paired with H1; when H1 fails, it reroutes to H2
    amb_movements = diff_h1["resource_movements"]["ambulances"]
    p4_mv = next((m for m in amb_movements if m["zone_id"] == "P4"), None)
    assert p4_mv is not None
    assert p4_mv["before_hospital_id"] == "H1"
    assert p4_mv["after_hospital_id"] == "H2"
    assert p4_mv["action"] == "rerouted"

    # 5. Reduce rescue teams to 1
    r_reduce = client.post("/failure", json={"type": "reduce_resources", "id": "rescue_teams", "amount": 1})
    assert r_reduce.status_code == 200
    plan_reduce = r_reduce.json()["plan"]
    assert plan_reduce["totals"]["resource_utilisation"]["rescue_teams_used"] == 1

    # 6. Reset restores baseline exactly
    r_reset = client.post("/reset")
    assert r_reset.status_code == 200
    reset_data = r_reset.json()
    assert reset_data["status"] == "ok"
    assert reset_data["diff"]["totals"]["unmet"]["delta"] == 0.0
    assert reset_data["diff"]["totals"]["people_assigned"]["delta"] == 0.0
    assert reset_data["plan"]["totals"]["total_rescued_by_boat"] == 800
